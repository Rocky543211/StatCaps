local locale = "en";
if (Turbine and Turbine.Engine and Turbine.Engine.GetLanguage) then
    local ok, language = pcall(Turbine.Engine.GetLanguage);
    local languages = Turbine.Language or {};
    if (ok and languages.German ~= nil and language == languages.German) then locale = "de";
    elseif (ok and languages.French ~= nil and language == languages.French) then locale = "fr"; end
end

local function escapePattern(text)
    return (string.gsub(text, "([^%w])", "%%%1"));
end

local sortedPhrases = {};
for language, dictionary in pairs(translations) do
    local phrases = {};
    for source in pairs(dictionary) do phrases[#phrases + 1] = source; end
    table.sort(phrases, function(a, b)
        if (#a == #b) then return a < b; end
        return #a > #b;
    end);
    sortedPhrases[language] = phrases;
end

function StatCapsLocalization.Text(text)
    if (type(text) ~= "string" or locale == "en") then return text; end
    local dictionary = translations[locale];
    for _, source in ipairs(sortedPhrases[locale]) do
        local replacement = dictionary[source];
        local pattern = escapePattern(source);
        if (string.match(source, "^%w+$")) then
            pattern = "%f[%w]" .. pattern .. "%f[%W]";
        end
        text = string.gsub(text, pattern, function() return replacement; end);
    end
    return text;
end

function StatCapsLocalization.Locale()
    return locale;
end
